/**
 * Admin UI strings — English and 简体中文.
 *
 * Language: saved choice (localStorage `rra.admin.lang`) → browser language →
 * English. Switching saves the choice and reloads /admin (the session token
 * lives in sessionStorage, so the admin stays signed in; unsaved edits still
 * trigger the browser's leave-page prompt).
 *
 * Server error messages are English; `errorText` puts a Chinese summary in
 * front of them, keyed by the stable error `code`.
 */
