export const lang: AdminLang = detectLang();
export const t: Messages = lang === 'zh-CN' ? zh : en;

/** Resolve a string-or-plural catalog entry. */
export const say = (entry: string | Plural, n = 0) => (typeof entry === 'function' ? entry(n) : entry);

/** Message for a failed request; in Chinese a translated summary comes first. */
export function errorText(error: unknown): string {
  const message = error instanceof Error ? error.message : String(error);
  if (!t.errors || !(error instanceof ApiError)) return message;
  const summary = t.errors[error.code];
  return summary && summary !== message ? `${summary}：${message}` : message;
}
