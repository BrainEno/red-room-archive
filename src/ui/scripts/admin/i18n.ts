export type AdminLang = 'en' | 'zh-CN';
export const LANG_KEY = 'rra.admin.lang';

export type TabId = 'Overview' | 'Articles' | 'More' | 'Newsletter' | 'Settings' | 'Files';

export function detectLang(): AdminLang {
  try {
    const saved = parseLocale(localStorage.getItem(LANG_KEY));
    if (saved) return saved;
  } catch {
    /* storage blocked — fall through */
  }
  const languages = navigator.languages?.length ? navigator.languages : [navigator.language];
  return negotiateLocale(languages.join(',')) ?? 'en';
}

export function setLang(next: AdminLang) {
  try {
    localStorage.setItem(LANG_KEY, next);
  } catch {
    /* storage blocked — the choice lasts for this page only */
  }
  location.reload();
}

